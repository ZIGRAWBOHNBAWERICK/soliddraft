#!/usr/bin/env python3
"""Git merge driver for Cargo.lock: a three-way merge of the locked packages.

Git runs a merge driver before it writes the merged manifests. In a tree-only
merge it never writes them, so Cargo cannot resolve them here. The driver merges the
package graph instead. Each side's changes to the base apply, package by package and dependency
by dependency. Cargo must still validate the result against the merged manifests.
If both sides changed the same package field incompatibly, or the merge removes a
package the result still references, the driver leaves the lockfile unmerged.
If Cargo's post-merge --locked check finds it stale, run cargo update --workspace.

Enable it in a clone (the repository's .gitattributes already names it for Cargo.lock):

    git config merge.cargo-lock.driver 'python3 ci/cargo-lock-merge.py %O %A %B %L'
"""
import re
import subprocess
import sys
import tomllib

HEADER = '# This file is automatically @generated by Cargo.\n# It is not intended for manual editing.\n'
FIELDS = ('name', 'version', 'source', 'checksum', 'dependencies', 'replace')


class Conflict(Exception):
    """Both sides changed the same thing; Git's conflict markers have to show it."""


def semver(text):
    """The ordering key of a semver version: numbers, then prerelease, then build metadata."""
    match = re.fullmatch(r'(\d+)\.(\d+)\.(\d+)(?:-([0-9A-Za-z.-]+))?(?:\+([0-9A-Za-z.-]+))?', text)
    if not match:
        raise Conflict(f'unreadable version {text!r}')
    identifiers = lambda part: [(0, int(i), '') if i.isdigit() else (1, 0, i) for i in part.split('.')]
    pre = (1, []) if match[4] is None else (0, identifiers(match[4]))
    build = [] if match[5] is None else identifiers(match[5])
    return int(match[1]), int(match[2]), int(match[3]), pre, build


def package_key(package):
    return package['name'], package['version'], package.get('source')


def sort_key(key):
    name, version, source = key
    return name, semver(version), source or ''


def parse(text):
    """The lockfile's top-level settings and its packages, each with resolved dependency keys."""
    try:
        data = tomllib.loads(text)
    except tomllib.TOMLDecodeError as error:
        raise Conflict(f'unreadable lockfile: {error}') from error
    packages = data.pop('package', [])
    if any(set(package) - set(FIELDS) for package in packages):
        raise Conflict('a package has a field this driver does not know')
    by_key = {}
    for package in packages:
        key = package_key(package)
        if key in by_key:
            raise Conflict(f'package {key} is listed twice')
        by_key[key] = package
    resolved = {}
    for key, package in by_key.items():
        entry = {field: package[field] for field in FIELDS if field in package and field != 'dependencies'}
        if 'dependencies' in package:
            entry['dependencies'] = frozenset(resolve(reference, by_key) for reference in package['dependencies'])
        resolved[key] = entry
    return data, resolved


def resolve(reference, packages):
    """The package a dependency line names: "name", "name version" or "name version (source)"."""
    match = re.fullmatch(r'(\S+)(?: (\S+))?(?: \((.+)\))?', reference)
    if not match:
        raise Conflict(f'unreadable dependency {reference!r}')
    name, version, source = match.groups()
    found = [key for key in packages if key[0] == name and (version is None or key[1] == version)
             and (source is None or key[2] == source)]
    if len(found) != 1:
        raise Conflict(f'dependency {reference!r} names {len(found)} packages')
    return found[0]


def reference(key, packages):
    """Cargo's spelling: the name alone unless other versions or sources of it are locked too."""
    name, version, source = key
    same_name = [other for other in packages if other[0] == name]
    if len(same_name) == 1:
        return name
    if sum(other[1] == version for other in same_name) == 1:
        return f'{name} {version}'
    return f'{name} {version} ({source})'


def three_way(base, ours, theirs, what):
    if ours == theirs:
        return ours
    if ours == base:
        return theirs
    if theirs == base:
        return ours
    raise Conflict(f'both sides changed {what}')


def merge_entries(key, base, ours, theirs):
    base = base or {}
    merged = {}
    for field in FIELDS:
        values = [entry.get(field) for entry in (base, ours, theirs)]
        if field == 'dependencies' and values[1] != values[2]:
            old, left, right = (value or frozenset() for value in values)
            # Each side's added and removed dependencies apply; neither side's change is lost.
            value = frozenset((left | right) - (old - left) - (old - right)) or None
        else:
            value = three_way(*values, f'{field} of {key}')
        if value is not None:
            merged[field] = value
    return merged


def local_versions(packages):
    versions = {}
    for name, version, source in packages:
        if source is None:
            versions.setdefault(name, set()).add(version)
    return versions


def merge(base_text, ours_text, theirs_text):
    (base_top, base), (ours_top, ours), (theirs_top, theirs) = map(parse, (base_text, ours_text, theirs_text))
    top = {}
    for name in sorted(base_top.keys() | ours_top.keys() | theirs_top.keys()):
        value = three_way(base_top.get(name), ours_top.get(name), theirs_top.get(name), f'lockfile setting {name}')
        if value is not None:
            top[name] = value
    if set(top) - {'version'}:
        raise Conflict('the lockfile has settings this driver does not know')
    # The version is part of the package key. Competing bumps of one workspace crate
    # otherwise look like deleting the old package and adding two unrelated packages.
    base_versions, our_versions, their_versions = map(local_versions, (base, ours, theirs))
    for name in sorted(base_versions.keys() | our_versions.keys() | their_versions.keys()):
        three_way(base_versions.get(name), our_versions.get(name), their_versions.get(name),
                  f'version of local package {name}')
    packages = {}
    for key in base.keys() | ours.keys() | theirs.keys():
        old, left, right = base.get(key), ours.get(key), theirs.get(key)
        if left is None and right is None:
            continue
        if left is None or right is None:
            kept = left if left is not None else right
            if old is None:
                packages[key] = kept          # added on one side
            elif kept != old:
                raise Conflict(f'{key} was removed on one side and changed on the other')
            continue
        packages[key] = merge_entries(key, old, left, right)
    for key, entry in packages.items():
        missing = entry.get('dependencies', frozenset()) - packages.keys()
        if missing:
            raise Conflict(f'{key} depends on {min(missing, key=sort_key)}, which the other side removed')
    return render(top, packages)


def quoted(value):
    return '"' + value.replace('\\', '\\\\').replace('"', '\\"') + '"'


def render(top, packages):
    lines = [HEADER.rstrip('\n')]
    if 'version' in top:
        lines.append(f'version = {top["version"]}')
    for key in sorted(packages, key=sort_key):
        entry = packages[key]
        lines += ['', '[[package]]']
        for field in FIELDS:
            if field not in entry:
                continue
            if field == 'dependencies':
                # Cargo sorts dependency lines by name, then by the version and source it spells.
                spelled = sorted((dep[0], *reference(dep, packages).split(' ', 1)[1:]) for dep in entry[field])
                lines.append('dependencies = [')
                lines += [f' {quoted(" ".join(parts))},' for parts in spelled]
                lines.append(']')
            else:
                lines.append(f'{field} = {quoted(entry[field])}')
    return '\n'.join(lines) + '\n'


def main(argv):
    if len(argv) not in (4, 5):
        sys.exit('usage: cargo-lock-merge.py BASE OURS THEIRS [MARKER_SIZE]')
    base_path, ours_path, theirs_path = argv[1:4]
    texts = []
    for path in (base_path, ours_path, theirs_path):
        with open(path, encoding='utf-8') as file:
            texts.append(file.read())
    try:
        result = merge(*texts)
    except Conflict as error:
        print(f'cargo-lock-merge: {error}; leaving the lockfile unmerged', file=sys.stderr)
        marker = [f'--marker-size={argv[4]}'] if len(argv) == 5 else []
        return subprocess.run(['git', 'merge-file', *marker, ours_path, base_path, theirs_path]).returncode or 1
    with open(ours_path, 'w', encoding='utf-8', newline='\n') as file:
        file.write(result)
    return 0


if __name__ == '__main__':
    sys.exit(main(sys.argv))
